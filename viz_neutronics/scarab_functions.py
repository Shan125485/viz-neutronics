def storeCoreBuilder(core_builder, z_pin: np.ndarray, x_assem, y_assem, z_assem, newpath):

    # make an output folder to store outputs
    if not os.path.exists(newpath):
        os.makedirs(newpath)

    assembly_powers = core_builder.compute_assembly_powers()
    pin_power = core_builder.compute_pin_powers(z_pin)
    x_pin_centers = core_builder.x_pin_centers
    y_pin_centers = core_builder.y_pin_centers

    solver = core_builder.solver

    logger.info('Making coreBuilder dictionary')
    dictionary = {  # all values are strings so that they get printed into a readable format
        'x_pin_centers': x_pin_centers.tolist(),
        'y_pin_centers': y_pin_centers.tolist(),
        'core_form_factors': core_builder.core_form_factors(x_pin_centers, y_pin_centers, z_pin).tolist(),
        'keff': solver.keff,
        'keff_tolerance': solver.keff_tolerance,
        'avg_flux': solver.avg_flux().tolist(),
        'avg_power': solver.avg_power().tolist(),
        'flux_pinwise': solver.flux(x_pin_centers, y_pin_centers, z_pin).tolist(),
        'flux_assembly_wise': solver.flux(x_assem, y_assem, z_assem).tolist(),
        'flux_tolerance': solver.flux_tolerance,
        'power_pinwise': pin_power.tolist(),
        'power_assembly_wise': assembly_powers.tolist(),
        'ngroups': solver.ngroups
    }
    logger.info('dumping to json %s', newpath +
                'coreBuilder_output.json')

    with open(newpath + 'coreBuilder_output.json', 'w') as f:
        json.dump(dictionary, f, indent=2)


def readCoreBuilder(filepath):
    res = readOutputs(filepath, print_output=True)

    logger.info("Beginning some useful post-processing of Scarabée results:")

    flux_pinwise_dict = {}
    flux_assembly_wise_dict = {}
    avg_flux_dict = {}

    for i in range(res.ngroups):

        key = 'flux_pinwise' + str(i)
        logger.debug('Adding dictionary entry %s', key)
        value = np.array(res.flux_pinwise)[i, :, :, 0]
        flux_pinwise_dict[key] = value

        key_assem = 'flux_assembly_wise' + str(i)
        logger.debug('Adding dictionary entry %s', key_assem)
        value_assem = np.array(res.flux_assembly_wise)[i, :, :, 0]
        flux_assembly_wise_dict[key_assem] = value_assem

        key_avg = 'avg_flux' + str(i)
        logger.debug('Adding dictionary entry %s', key_avg)
        value_avg = np.array(res.avg_flux)[i, :, :, 0]
        avg_flux_dict[key_avg] = value_avg
    setattr(res, 'flux_pinwise', flux_pinwise_dict)
    setattr(res, 'flux_assembly_wise', flux_assembly_wise_dict)
    setattr(res, 'avg_flux', avg_flux_dict)

    avg_power = np.array(res.avg_power)
    mean_power = np.mean(avg_power)

    logger.debug(
        " Normalising the average power by its mean value, %s", mean_power)

    avg_power /= mean_power  # Normalise
    avg_power = avg_power[:, :, 0]
    setattr(res, 'avg_power', avg_power)

    setattr(res, 'power_pinwise', np.array(res.power_pinwise)[:, :, 0])
    setattr(res, 'power_assembly_wise', np.array(
        res.power_assembly_wise)[:, :])
    setattr(res, 'core_form_factors', np.array(res.core_form_factors)[:, :, 0])

    return res


def plotFromNodalResObject(resScarab, paramName, normalise_by_mean='all', vmax=None, vmin=None, plotting=True, aspect_ratio=1, indices=None, mgID=None, tol=1e-16, newpath='outputs', annotate=False, cmap_colour='magma', fontsize=2, colour='white', dp=3, view_geometry=None):
    """ Separate the plotting of results object from reading it, so that we don't have to read the open and load the same json file every time we plot something."""
    # Check parameter type
    if type(getattr(resScarab, paramName)) == dict:
        dataDict = getattr(resScarab, paramName)
        attrFoundFlag = False
        for key in dataDict.keys():
            if key[-1] == str(int(mgID)):
                logger.info(
                    'Parsing results to find match to mgID %s, %s', mgID, key)
                attrFoundFlag = True
                value = dataDict[key]
        if attrFoundFlag:
            pass
        else:
            raise ValueError(
                'Parameter {} with mgID {} for plotting was not found'.format(paramName, mgID))

    else:
        value = np.array(getattr(resScarab, paramName))
        mgID = ''  # set for plotting label

    keff = resScarab.keff

    value = apply_indices(indices, value)
    

    if len(value) == 0:
        raise ValueError('Length of values array is 0!')

    if view_geometry is not None:
        ny, nx = value.shape
        if view_geometry == 'quarter':
            # want to reduce the amount of data to just a quarter
            value = value[: (ny+1) // 2, nx // 2:]
        if view_geometry == 'octant':
            value = value[: (ny+1) // 2, nx // 2:]  # first reduce to quarter

            value = octantFromQuart(value)

    value = normalise_plots(
        value, normalise_by_mean=normalise_by_mean, tol=tol)

    if plotting:

        fig, ax1 = plot.subplots(constrained_layout=True)

        values_masked = np.ma.masked_where(value < tol, value)

        val_plot = ax1.imshow(values_masked, cmap=cmap_colour, vmax=vmax,
                              vmin=vmin, origin='lower', aspect=aspect_ratio)

        ax1 = label_plot(annotate, value, ax1,
                         fontsize=fontsize, color=colour, dp=dp)

        fig.colorbar(val_plot, ax=ax1).minorticks_on()

        fig.suptitle('Scarabee ' + paramName +
                     ', $k_{{eff}}$={:.5f}'.format(keff) + '\n{}: Normalised by the mean of {} values\nMax: {:.3f}, Min: {:.3f}'.format(
                         paramName + str(mgID), normalise_by_mean, np.max(values_masked), np.min(values_masked)))

        plot.savefig(newpath + '/' + paramName +
                     str(mgID) + '_nodal.svg')
        plot.close()

    return value



    

