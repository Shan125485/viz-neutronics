def plotFissRateCompareAssem_MOCMC(outputFileMC: str, outputFileMOC: str, name='assembly', newpath='outputs', rmse_relative_to=None, cmap_colour='Reds', normalise_by_mean='all', annotate=False, fontsize: float = 2,
        colour: str = 'black',
        dp: float = 3,):
    """_summary_

    Args:
        outputFileMC (_type_): _description_
        binFileMOC (_type_): _description_
        scarab_text_log (_type_): _description_
        name (_type_, optional): _description_. Defaults to 'assembly'.
    """    """"""

    outputs_filepath = newpath + '/'
    if not os.path.exists(outputs_filepath):
        os.makedirs(outputs_filepath)

    resScarab = readJSON(outputFileMOC)  # read Scarabee output

    # keff comparison
    keff_SCONE, keff_scarab, keff_diff = compareKeff_ScarabSCONE(
        outputFileMOC, outputFileMC)

    # Fission rate comparison
    tallyname = 'pinFiss'
    fissrateMC, fissrateMC_std = plotSpatialTallyMC(
        outputFileMC, tallyname, plotting=False, normalise_by_mean=normalise_by_mean)
    fissrateScarab = np.array(resScarab['form_factors'], dtype=float)
    fissrateScarab = normalise_plots(fissrateScarab, normalise_by_mean=normalise_by_mean)
    diff = (fissrateScarab - fissrateMC) / fissrateMC

    # Extract Metadata
    # exclude nan values for max calculation but keep them in the plot for clear visualisation of gadolinia and guide tubes
    max_error = np.max(diff[~np.isnan(diff)])
    min_error = np.min(diff[~np.isnan(diff)])

    rms = rmsError(fissrateMC, fissrateScarab, relative_to=rmse_relative_to)

    # plotting
    fig, ax = plot.subplots()
    val = ax.imshow(abs(diff), cmap=cmap_colour, origin='lower')
    ax = label_plot(annotate, abs(diff), ax, fontsize=fontsize, color=colour, dp=dp)
    fig.colorbar(val, ax=ax).minorticks_on()

    fig.suptitle(name + ': Scarabee MOC vs SCONE MC, '
                 '(Abs) relative difference in fission rate. \nMax error={:.2%}, '
                 'min error={:.2%}, \nRMSE={:.2%} relative to {}. \n$k_{{MC}}={:.5f}$, '
                 '$k_{{MOC}}={:.5f}$, diff={:.0f} pcm'.format(max_error, min_error, rms, rmse_relative_to, keff_SCONE, keff_scarab, keff_diff))
    plot.savefig(outputs_filepath + '/' + 'compare_MOC_MC_' +
                 tallyname + '_' + name + '.svg')
    plot.close()


