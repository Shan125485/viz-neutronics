def readDiffusionData(diff_data: scrb.DiffusionData):
    """Returns a dictionary containing diffusion data"""
    ngroups = diff_data.ngroups

    D = np.zeros(ngroups)
    Ea = np.zeros(ngroups)
    Er = np.zeros(ngroups)
    Ef = np.zeros(ngroups)
    vEf = np.zeros(ngroups)
    nu = np.zeros(ngroups)
    chi = np.zeros((ngroups))
    Es = np.zeros([ngroups, ngroups])

    for g_out in range(ngroups):
        D[g_out] = diff_data.D(g_out)
        Ea[g_out] = diff_data.Ea(g_out)
        Er[g_out] = diff_data.Er(g_out)
        Ef[g_out] = diff_data.Ef(g_out)
        vEf[g_out] = diff_data.vEf(g_out)
        nu[g_out] = diff_data.nu(g_out)
        chi[g_out] = diff_data.chi(g_out)
        for g_in in range(ngroups):
            Es[g_in][g_out] = diff_data.Es(g_in, g_out)

    data = {
        'adf': diff_data.adf.tolist(),
        'cdf': diff_data.cdf.tolist(),
        'D': D.tolist(),
        'Ea': Ea.tolist(),
        'Er': Er.tolist(),
        'Ef': Ef.tolist(),
        'vEf': vEf.tolist(),
        'nu': nu.tolist(),
        'chi': chi.tolist(),
        'Es': Es.tolist()
    }

    return data


