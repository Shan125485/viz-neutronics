def findKeff_fromFuelAssembly(scarab_text_log: str):
    """This works specifically for PWR assembly output log files. 
    Taking the second instance of keff seems to work, but 
    sometimes when running a full core, the individual fuel 
    assembly logs seem to get lost. I think the current set-up 
    in EPR core works well for now.

    Args:
        scarab_text_log (str): .txt file generated by Scarabee for a fuel assembly 

    Returns:
       float: The k-eff (or k-inf) for the fuel assembly
    """
    file = open(scarab_text_log, 'r')   # Read scarabee keff from text log
    keff_list = []
    counter = 0
    for line in file:
        if re.search('Kinf', line):
            keff_list.append(float(line.split()[-1]))
            if counter == 1:  # take the second instance of kinf
                break
            else:
                counter += 1
    keff_scarab = keff_list[-1]  # take the last iteration value
    file.close()
    return keff_scarab


def storeAssemblyJSON(assembly, name, outputDir, plotting=True, colour_map='magma'):
    """
    Input is a PWRAssembly object that has been solved (using MOC). Extract form factors, keff and max and min pin power.
    Returns the dictionary containing this information, and also plots the power distribution. Creates a human-readable JSON file.
    """
    logger.info('Storing %s assembly MOC data', name)
    outputFilePath = outputDir + '/' + name

    # Extract assembly data
    form_factors = assembly.form_factors.form_factors
    keff = assembly.keff
    max_pin_power = np.max(form_factors)
    logger.info('Calculating minimum non-zero pin powers')
    min_pin_power = np.min(form_factors[form_factors > 1e-6])

    data = {
        'name': name,
        'keff': keff,
        'max_pin_power': max_pin_power,
        'min_pin_power': min_pin_power,
        'form_factors': form_factors.tolist()
    }

    data.update(readDiffusionData(assembly.diffusion_data))

    with open(outputFilePath + "_data.json", "w") as f:
        json.dump(data, f, indent=2)

    if plotting:
        plotAssemFormFactors(outputFilePath + "_data.json",
                             outputDir, colour_map)

    return data


